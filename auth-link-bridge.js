(() => {
  const params = new URLSearchParams(window.location.hash.slice(1));
  const status = document.getElementById('status');
  const verifyButton = document.getElementById('verify');
  const openLink = document.getElementById('open');
  const tokenHash = params.get('token_hash');
  const accessToken = params.get('access_token');
  const refreshToken = params.get('refresh_token');

  const clearSensitiveFragment = () => {
    history.replaceState(null, '', window.location.pathname + window.location.search);
  };

  const fail = (message) => {
    status.textContent = message;
    status.classList.add('error');
    verifyButton.hidden = true;
    openLink.hidden = true;
  };

  const offerSession = (access, refresh) => {
    const callback = new URL('dpc://auth/callback');
    // The released app accepts callback credentials in its query or fragment.
    // Use the query deliberately because the failing iOS handoff delivered the
    // custom-scheme URL while dropping its fragment.
    callback.search = new URLSearchParams({
      access_token: access,
      refresh_token: refresh,
      token_type: 'bearer',
    }).toString();
    openLink.href = callback.toString();
    openLink.hidden = false;
    verifyButton.hidden = true;
    status.textContent = 'Your sign-in is ready. Opening DPC…';
    window.location.assign(openLink.href);
  };

  // Continue to support links generated by the previous Supabase template,
  // where Supabase verified the OTP before redirecting the session here.
  if (accessToken && refreshToken) {
    clearSensitiveFragment();
    offerSession(accessToken, refreshToken);
    return;
  }

  if (!tokenHash || params.get('error')) {
    fail('This sign-in link expired or could not be used. Return to DPC and request a new link.');
    return;
  }

  verifyButton.addEventListener('click', async () => {
    verifyButton.disabled = true;
    verifyButton.textContent = 'Verifying…';
    status.textContent = 'Confirming your secure sign-in…';
    clearSensitiveFragment();

    try {
      const response = await fetch('/api/auth-link-bridge', {
        method: 'POST',
        headers: { 'content-type': 'application/json' },
        body: JSON.stringify({ token_hash: tokenHash }),
        credentials: 'omit',
        cache: 'no-store',
      });
      const result = await response.json();
      if (!response.ok || result?.success !== true) throw new Error('verification_failed');
      offerSession(result.data.access_token, result.data.refresh_token);
    } catch {
      fail('This sign-in link expired or could not be used. Return to DPC and request a new link.');
    }
  });
})();
